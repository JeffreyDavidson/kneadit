<div class="legal-section" id="overview">
<h2>1. Overview</h2>
<p>This Privacy Policy describes how Infinity Digital LLC ("we," "us," or "our") collects, uses, and protects information when you use KneadIt ("the Service") at getkneadit.app and its subdomains.</p>
<p>This policy applies to Baker accounts (bakery owners using the platform) and End Customers (people who place orders through Baker storefronts).</p>
</div>

<div class="legal-section" id="collect">
<h2>2. Information We Collect</h2>

<h3>Account Information (Bakers)</h3>
<ul>
<li>Name, email address, and password</li>
<li>Bakery name and subdomain</li>
<li>Business information (phone number, address, if provided)</li>
</ul>

<h3>Billing Information</h3>
<ul>
<li>Payment details are collected and processed by <strong>Stripe</strong>. We do not store your full credit card number on our servers.</li>
<li>We receive from Stripe: card type, last four digits, expiration date, and billing address for record-keeping.</li>
</ul>

<h3>End Customer Information (collected by Bakers through storefronts)</h3>
<ul>
<li>Name, email, phone number</li>
<li>Order details and delivery/pickup preferences</li>
<li>Any other information provided during the ordering process</li>
</ul>

<h3>Usage Data</h3>
<ul>
<li>Log data such as IP address, browser type, and pages visited</li>
<li>Feature usage patterns within the platform</li>
<li>We do <strong>not</strong> currently use third-party analytics tools</li>
</ul>
</div>

<div class="legal-section" id="use">
<h2>3. How We Use Your Information</h2>
<p>We use the information we collect to:</p>
<ul>
<li>Provide, maintain, and improve the Service</li>
<li>Process subscription payments and manage your account</li>
<li>Send transactional emails (order confirmations, password resets, account notifications)</li>
<li>Respond to support requests and communicate with you</li>
<li>Enforce our Terms of Service and protect against misuse</li>
<li>Comply with legal obligations</li>
</ul>
<p>We do <strong>not</strong> sell, rent, or share your personal information with third parties for marketing purposes.</p>
</div>

<div class="legal-section" id="third-party">
<h2>4. Third-Party Services</h2>
<p>We use the following third-party services to operate KneadIt:</p>

<h3>Stripe</h3>
<p>Processes subscription payments. Stripe collects and manages payment information under its own <a href="https://stripe.com/privacy" target="_blank" rel="noopener">Privacy Policy</a>.</p>

<h3>Resend</h3>
<p>Delivers transactional emails (from hello@getkneadit.app). Email addresses are shared with Resend for delivery purposes. See <a href="https://resend.com/legal/privacy-policy" target="_blank" rel="noopener">Resend's Privacy Policy</a>.</p>

<h3>Cloudflare</h3>
<p>Provides content delivery, DNS, and security services. Cloudflare may process connection metadata (IP addresses, request headers). See <a href="https://www.cloudflare.com/privacypolicy/" target="_blank" rel="noopener">Cloudflare's Privacy Policy</a>.</p>

<h3>PayPal (Baker-configured)</h3>
<p>Bakers may use PayPal to process payments from their End Customers. KneadIt does not process these payments — PayPal's relationship is directly with the Baker and their customers.</p>
</div>

<div class="legal-section" id="cookies">
<h2>5. Cookies &amp; Tracking</h2>
<p>KneadIt uses only <strong>essential session cookies</strong> required for the Service to function (authentication, CSRF protection). We do not use:</p>
<ul>
<li>Third-party tracking cookies</li>
<li>Advertising cookies</li>
<li>Analytics cookies</li>
</ul>
<p>Your browser may allow you to disable cookies, but doing so may prevent you from using certain features of the Service.</p>
</div>

<div class="legal-section" id="retention">
<h2>6. Data Retention</h2>
<ul>
<li><strong>Active accounts:</strong> Data is retained for as long as your account is active.</li>
<li><strong>Canceled accounts:</strong> Data is retained for 30 days after cancellation to allow for reactivation or export, then permanently deleted.</li>
<li><strong>Billing records:</strong> Retained as required by applicable tax and financial regulations.</li>
<li><strong>Support communications:</strong> Retained for a reasonable period to provide ongoing service.</li>
</ul>
</div>

<div class="legal-section" id="baker-responsibility">
<h2>7. Baker Responsibility for Customer Data</h2>
<p>Bakers who use KneadIt collect and manage their own End Customers' data through their storefronts. As a Baker, you are responsible for:</p>
<ul>
<li>Complying with all applicable privacy laws regarding your customers' data</li>
<li>Informing your End Customers about what data you collect and how you use it</li>
<li>Handling data access, correction, and deletion requests from your End Customers</li>
<li>Ensuring your use of customer data complies with local regulations</li>
</ul>
<p>KneadIt acts as a data processor on behalf of Bakers (the data controllers) for End Customer data. We process this data only to provide the Service and do not use End Customer data for our own independent purposes.</p>
</div>

<div class="legal-section" id="children">
<h2>8. Children's Privacy (COPPA)</h2>
<p>KneadIt is not directed at children under the age of 13. We do not knowingly collect personal information from children under 13. If you believe a child under 13 has provided us with personal information, please contact us at <a href="mailto:hello@getkneadit.app">hello@getkneadit.app</a> and we will promptly delete such information.</p>
<p>Baker accounts require users to be at least 18 years old.</p>
</div>

<div class="legal-section" id="security">
<h2>9. Data Security</h2>
<p>We implement industry-standard security measures to protect your information, including:</p>
<ul>
<li>Encryption of data in transit (TLS/SSL)</li>
<li>Secure password hashing</li>
<li>Regular security updates and monitoring</li>
<li>Access controls limiting who can view your data</li>
</ul>
<p>While we strive to protect your information, no method of transmission or storage is 100% secure. We cannot guarantee absolute security.</p>
</div>

